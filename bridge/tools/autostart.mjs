// dsh-link/bridge/tools/autostart.mjs — 登录自启安装/卸载（无需管理员，不写注册表）。
//
// 原理：把生成的 `dsh-link-bridge.vbs` 放到当前用户的
//   %APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup\dsh-link-bridge.vbs
// 该 vbs 用**运行本脚本的 node 绝对路径**隐藏启动 bridge/server.mjs（cwd=bridge 目录）。
// 防双开由 server.mjs 启动自检负责：已在运行则打印提示并 exit 0。
//
// Node 解析顺序：node-path.txt（bridge 目录，一行绝对路径）→ %DSH_NODE_PATH% → process.execPath。
// 本文件不含任何机器私有路径。
//
// 用法：node tools/autostart.mjs install | uninstall | status
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const BRIDGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVER_JS = path.join(BRIDGE_DIR, 'server.mjs');
const STARTUP_DIR = path.join(
  process.env.APPDATA || path.join(process.env.USERPROFILE || '', 'AppData', 'Roaming'),
  'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup',
);
const TARGET_VBS = path.join(STARTUP_DIR, 'dsh-link-bridge.vbs');

/** 解析 node 绝对路径：node-path.txt → %DSH_NODE_PATH% → 当前进程的 node。 */
function resolveNodeExe() {
  const candidates = [];
  const nodePathFile = path.join(BRIDGE_DIR, 'node-path.txt');
  try {
    const text = fs.readFileSync(nodePathFile, 'utf8').trim();
    if (text) candidates.push(text);
  } catch { /* 无 node-path.txt 时忽略 */ }
  if (process.env.DSH_NODE_PATH) candidates.push(process.env.DSH_NODE_PATH);
  candidates.push(process.execPath);
  for (const candidate of candidates) {
    try {
      if (candidate && fs.existsSync(candidate)) return candidate;
    } catch { /* 忽略非法路径 */ }
  }
  return process.execPath;
}

const NODE_EXE = resolveNodeExe();

/** 生成放启动文件夹的 vbs（安装时写入当前机器的绝对路径，位置无关）。
 *  注意两点（实测踩坑）：
 *   1) 文件必须存成 UTF-16LE + BOM，WSH 才会按 Unicode 解析含中文的路径字面量；
 *   2) VBS 字符串里反斜杠不转义，路径必须是单反斜杠（写成 \\ 会被当成两个字面反斜杠而找不到文件）。
 */
function generateVbs() {
  return [
    "' dsh-link bridge - login autostart (generated by dsh-link/bridge/tools/autostart.mjs)",
    "' Hidden start of node server.mjs. Double-start is prevented by server.mjs itself.",
    'Option Explicit',
    'Dim fso, shell, cmd',
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    'Set shell = CreateObject("WScript.Shell")',
    `If Not fso.FileExists("${NODE_EXE}") Then WScript.Quit 0`,
    `If Not fso.FileExists("${BRIDGE_DIR}\\server.mjs") Then WScript.Quit 0`,
    `shell.CurrentDirectory = "${BRIDGE_DIR}"`,
    `cmd = Chr(34) & "${NODE_EXE}" & Chr(34) & " " & Chr(34) & "${BRIDGE_DIR}\\server.mjs" & Chr(34)`,
    'shell.Run cmd, 0, False',
    '',
  ].join('\r\n');
}

function install() {
  if (!fs.existsSync(NODE_EXE)) throw new Error(`node 不存在: ${NODE_EXE}（可用 node-path.txt / DSH_NODE_PATH 指定）`);
  if (!fs.existsSync(SERVER_JS)) throw new Error(`server.mjs 不存在: ${SERVER_JS}`);
  fs.mkdirSync(STARTUP_DIR, { recursive: true });
  const text = generateVbs();
  // UTF-16LE + BOM（WSH 正确处理中文路径；纯 UTF-8 会被按 ANSI 读成乱码）
  const buffer = Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(text, 'utf16le')]);
  fs.writeFileSync(TARGET_VBS, buffer);
  console.log('[OK] 登录自启已安装（UTF-16LE/BOM vbs）');
  console.log(`  启动文件: ${TARGET_VBS}`);
  console.log(`  node:     ${NODE_EXE}`);
  console.log(`  bridge:   ${SERVER_JS}`);
  console.log('  说明: 每次登录 Windows 时隐藏启动 bridge；已在运行则自动跳过（防双开）。');
  console.log('  卸载: 运行 uninstall-autostart.cmd');
  return 0;
}

function uninstall() {
  if (fs.existsSync(TARGET_VBS)) {
    fs.rmSync(TARGET_VBS, { force: true });
    console.log('[OK] 登录自启已卸载');
    console.log(`  已删除: ${TARGET_VBS}`);
  } else {
    console.log('[OK] 登录自启本就未安装（无需删除）');
    console.log(`  目标不存在: ${TARGET_VBS}`);
  }
  return 0;
}

function status() {
  const installed = fs.existsSync(TARGET_VBS);
  console.log(JSON.stringify({
    installed,
    startupVbs: TARGET_VBS,
    bridgeDir: BRIDGE_DIR,
    serverJs: SERVER_JS,
    nodeExe: NODE_EXE,
    nodeExists: fs.existsSync(NODE_EXE),
  }, null, 2));
  return installed ? 0 : 1;
}

const action = process.argv[2] || 'status';
try {
  const code = action === 'install' ? install() : action === 'uninstall' ? uninstall() : status();
  process.exit(code);
} catch (error) {
  console.error(`[FAIL] ${error.message}`);
  process.exit(1);
}
