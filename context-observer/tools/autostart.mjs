/**
 * dsh-link/context-observer/tools/autostart.mjs — 登录自启的安装 / 卸载 / 状态（本机、当前用户、不需要管理员）。
 *
 * 做法与 dsh-link bridge 一致：在
 *   %APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup\dsh-link-context-observer.vbs
 * 放/删一个**生成了绝对路径**的隐藏启动 vbs（不写注册表、不改系统设置）。
 *
 * 用法：
 *   node tools/autostart.mjs install     # 安装登录自启
 *   node tools/autostart.mjs uninstall   # 卸载登录自启
 *   node tools/autostart.mjs status      # 查看是否安装 / 观察器是否在跑
 */

import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OBSERVER_DIR = path.dirname(HERE);
const NODE_EXE = process.env.DSH_NODE_EXE
  || 'C:\\Users\\PC\\.dsh\\dsh-runtimes\\dsh-primary-runtime\\dependencies\\node\\bin\\node.exe';
const STARTUP_DIR = path.join(
  process.env.APPDATA ?? path.join(os.homedir(), 'AppData', 'Roaming'),
  'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup',
);
const TARGET_FILE = path.join(STARTUP_DIR, 'dsh-link-context-observer.vbs');
const LOCK_FILE = path.join(OBSERVER_DIR, 'observer.lock');

const vbs = (file) => [
  "' dsh-link context-observer - login autostart (generated by tools/autostart.mjs; do not edit)",
  "' Hidden start of the local context observer. No admin required; no registry writes.",
  'Option Explicit',
  'Dim fso, shell, observerDir, nodeExe, cmd',
  'Set fso = CreateObject("Scripting.FileSystemObject")',
  'Set shell = CreateObject("WScript.Shell")',
  `observerDir = "${OBSERVER_DIR.replaceAll('"', '""')}"`,
  `nodeExe = "${NODE_EXE.replaceAll('"', '""')}"`,
  'If Not fso.FileExists(nodeExe) Then WScript.Quit 1',
  'If Not fso.FileExists(observerDir & "\\observer.mjs") Then WScript.Quit 1',
  'shell.CurrentDirectory = observerDir',
  'cmd = Chr(34) & nodeExe & Chr(34) & " " & Chr(34) & observerDir & "\\observer.mjs" & Chr(34)',
  'shell.Run cmd, 0, False',
  '',
].join('\r\n');

function observerRunning() {
  try {
    const info = JSON.parse(readFileSync(LOCK_FILE, 'utf8'));
    const pid = Number(info?.pid);
    if (!Number.isFinite(pid) || pid <= 0) return { running: false, pid: null };
    try {
      process.kill(pid, 0);
      return { running: true, pid };
    } catch (error) {
      return { running: error && error.code === 'EPERM', pid };
    }
  } catch {
    return { running: false, pid: null };
  }
}

const action = (process.argv[2] ?? 'status').toLowerCase();

if (action === 'install') {
  if (!existsSync(NODE_EXE)) {
    console.error(`[FAIL] bundled node not found: ${NODE_EXE}`);
    process.exit(1);
  }
  if (!existsSync(path.join(OBSERVER_DIR, 'observer.mjs'))) {
    console.error(`[FAIL] observer.mjs not found in ${OBSERVER_DIR}`);
    process.exit(1);
  }
  mkdirSync(STARTUP_DIR, { recursive: true });
  writeFileSync(TARGET_FILE, vbs(), 'ascii');
  console.log(`[OK] autostart installed: ${TARGET_FILE}`);
  console.log(`[INFO] observer dir: ${OBSERVER_DIR}`);
  process.exit(0);
}

if (action === 'uninstall') {
  if (existsSync(TARGET_FILE)) {
    unlinkSync(TARGET_FILE);
    console.log(`[OK] autostart removed: ${TARGET_FILE}`);
  } else {
    console.log('[INFO] autostart was not installed');
  }
  process.exit(0);
}

if (action === 'status') {
  const installed = existsSync(TARGET_FILE);
  const running = observerRunning();
  console.log(`autostart: ${installed ? `installed (${TARGET_FILE})` : 'not installed'}`);
  console.log(`observer: ${running.running ? `running (pid=${running.pid})` : 'not running'}`);
  console.log(`observer dir: ${OBSERVER_DIR}`);
  process.exit(0);
}

console.error(`未知动作：${action}（可用：install / uninstall / status）`);
process.exit(1);
