// dsh-link/server/awareness/tools/autostart.mjs
// 管理「登录自启」：在 Windows 启动文件夹放/删一个隐藏启动 local-sync.mjs 的 VBS。
// 用法：
//   node tools/autostart.mjs install     # 安装登录自启（不运行）
//   node tools/autostart.mjs uninstall   # 卸载
//   node tools/autostart.mjs status      # 查看
// 说明：自启只是「登录时启动同步器」，是否启用由使用者自行决定；默认不会自动安装。
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const AWARENESS_DIR = resolve(HERE, '..')
const SYNC_SCRIPT = join(AWARENESS_DIR, 'local-sync.mjs')
// 用当前正在运行本脚本的 Node 可执行文件，避免写死任何机器私有路径
const NODE = process.execPath || 'node'
const STARTUP_DIR = process.env.APPDATA
  ? join(process.env.APPDATA, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup')
  : join(homedir(), 'AppData', 'Roaming', 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup')
const VBS_PATH = join(STARTUP_DIR, 'dsh-link-awareness-sync.vbs')

const VBS_CONTENT = [
  "' dsh-link awareness local-sync autostart (generated by tools/autostart.mjs)",
  'Set WShell = CreateObject("WScript.Shell")',
  `WShell.Run """${NODE}"" ""${SYNC_SCRIPT}"" --loop", 0, False`,
  '',
].join('\r\n')

const [command] = process.argv.slice(2)

if (command === 'install') {
  try {
    mkdirSync(STARTUP_DIR, { recursive: true })
    // UTF-16LE + BOM：路径含中文，WSH 按 ANSI 读会乱码 → 自启静默失效。
    writeFileSync(VBS_PATH, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(VBS_CONTENT, 'utf16le')]))
    console.log(`installed: ${VBS_PATH}`)
    console.log(`launch: "${NODE}" "${SYNC_SCRIPT}" --loop`)
  } catch (error) {
    console.error(`install failed: ${error?.message ?? error}`)
    process.exit(1)
  }
} else if (command === 'uninstall') {
  try {
    rmSync(VBS_PATH, { force: true })
    console.log(`uninstalled: ${VBS_PATH}`)
  } catch (error) {
    console.error(`uninstall failed: ${error?.message ?? error}`)
    process.exit(1)
  }
} else if (command === 'status') {
  console.log(JSON.stringify({
    installed: existsSync(VBS_PATH),
    vbsPath: VBS_PATH,
    syncScript: SYNC_SCRIPT,
    node: NODE,
    content: existsSync(VBS_PATH) ? readFileSync(VBS_PATH, 'utf8') : null,
  }, null, 2))
} else {
  console.error('usage: node tools/autostart.mjs install|uninstall|status')
  process.exit(2)
}
